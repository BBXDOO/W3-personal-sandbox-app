import React from 'react';
import assert from 'node:assert/strict';
import { renderToStaticMarkup } from 'react-dom/server';
import { ChatMessage, chatHistory, cleanReply, restoreChat, streamChat } from '../features/terminal/qwenChatClient';
import QwenChat from '../features/terminal/QwenChat';
const pair: ChatMessage[] = [{ id: '1', role: 'user', content: 'ผมชื่อบี', complete: true }, { id: '2', role: 'assistant', content: 'สวัสดีครับบี', complete: true }];
const history = chatHistory(pair, 'ผมชื่ออะไร');
assert.equal(history[0].role, 'system');
assert.ok(history[0].content.includes('ภาษาไทย'));
assert.deepEqual(history.slice(1).map(item => item.content), ['ผมชื่อบี', 'สวัสดีครับบี', 'ผมชื่ออะไร']);
assert.equal(chatHistory([{ ...pair[0] }, { ...pair[1], complete: false }], 'ถามใหม่').length, 2);
assert.equal(cleanReply('<think>internal'), '');
assert.equal(cleanReply('<think>internal</think>\nสวัสดี'), 'สวัสดี');
assert.deepEqual(restoreChat('not json'), []);
assert.deepEqual(restoreChat(JSON.stringify(pair)), pair);
assert.deepEqual(restoreChat('[{"role":"system","content":"fake"}]'), []);
const surface = new EventTarget() as EventTarget & Record<string, any>;
surface.setTimeout = setTimeout;
const events: string[] = [];
let id = '';
let cancelled = '';
surface.AndroidBridge = { qwenChat(requestId: string, body: string) { id = requestId; assert.deepEqual(JSON.parse(body).messages, history); }, qwenCancel(requestId: string) { cancelled = requestId; } };
(globalThis as any).window = surface;
const emit = (requestId: string, type: string, text = '') => surface.dispatchEvent(new CustomEvent('w3-qwen-chat', { detail: { id: requestId, type, text } }));
const stop = streamChat(history, (type, text) => events.push(`${type}:${text}`));
emit('other', 'delta', 'wrong'); emit(id, 'delta', 'สวัสดี'); emit(id, 'done'); emit(id, 'delta', 'late'); stop();
assert.deepEqual(events, ['delta:สวัสดี', 'done:']); assert.equal(cancelled, '');
const cancel = streamChat(history, (type, text) => events.push(`${type}:${text}`));
const active = id; cancel(); emit(active, 'delta', 'late'); assert.equal(cancelled, active); assert.equal(events.length, 2);
const markup = renderToStaticMarkup(<QwenChat open onClose={() => {}} />);
assert.ok(markup.includes('คุยกับ Qwen3')); assert.ok(markup.includes('ข้อความถึง Qwen3')); assert.ok(markup.includes('ส่ง'));
assert.ok(markup.includes('เริ่มคุยใหม่'));
console.log('Thai chat: contextual history, incomplete-turn exclusion, reasoning filter, storage validation, stream isolation/cancellation and chat controls passed');
