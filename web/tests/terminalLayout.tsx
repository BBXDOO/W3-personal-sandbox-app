import React from 'react';
import assert from 'node:assert/strict';
import { renderToStaticMarkup } from 'react-dom/server';
import { readFileSync } from 'node:fs';
import TerminalWorkspace from '../features/terminal/TerminalWorkspace';
import RepositoryPane from '../features/terminal/RepositoryPane';

(globalThis as any).window = {};
const html = renderToStaticMarkup(<TerminalWorkspace />);
assert.ok(!html.includes('ตั้งค่าครั้งแรก'));
assert.ok(!html.includes('terminal-setup'));
assert.ok(!html.includes('โฟลเดอร์ใหม่ เช่น'));
assert.ok(html.includes('เครื่องมือ Terminal'));
const explorer = html.indexOf('Explorer รายการไฟล์รีโป้');
const viewer = html.indexOf('พื้นที่เปิดดูไฟล์');
const shell = html.indexOf('Command shell ด้านล่าง');
assert.ok(explorer > 0 && viewer > explorer && shell > viewer);
assert.ok(html.indexOf('terminal-pane-divider') > viewer && html.indexOf('terminal-pane-divider') < shell);
assert.ok(html.indexOf('หน้าจอ shell') > shell);
assert.ok(html.indexOf('terminal-keys') > shell);
assert.ok(html.indexOf('คำสั่ง Terminal') > html.indexOf('terminal-keys'));
assert.match(html, /role="separator"[^>]*aria-orientation="horizontal"/);
const collapsed = renderToStaticMarkup(<RepositoryPane session="test" initialRoot="~/repo" available connected explorerOpen={false} onToggle={() => {}} onUpgrade={() => {}} />);
assert.ok(collapsed.includes('repository-panes-collapsed'));
assert.ok(collapsed.includes('aria-label="เปิดรายการไฟล์"'));
assert.match(collapsed, /aria-label="Explorer รายการไฟล์รีโป้" hidden=""/);
const css = readFileSync('web/index.css', 'utf8');
assert.match(css, /\.terminal-toolbar\s*\{[^}]*flex-wrap:\s*nowrap/);
assert.match(css, /\.terminal-three-panes\s*\{[^}]*display:\s*grid/);
assert.match(css, /\.repository-panes\s*\{[^}]*grid-template-columns:/);
assert.match(css, /\.terminal-pane-divider\s*\{[^}]*touch-action:\s*none/);
console.log('Three-pane layout: Explorer, file viewer, bottom shell, resize and collapse controls passed');
